from __future__ import annotations

import pandas as pd


# ============================================================
# 生存分析の共通設定
# ============================================================

# LIFULL HOME'S 掲載期間データの収録期間末日
OBSERVATION_END = pd.Timestamp("2024-03-31")

# 今回の研究で主に使用する掲載開始年
TARGET_YEARS = [
    2020,
    2021,
    2022,
    2023,
]


# ============================================================
# 生存分析用データ作成
# ============================================================

def prepare_survival_data(
    df: pd.DataFrame,
    years: list[int] | None = None,
) -> pd.DataFrame:
    """
    Kaplan-Meier法および生存モデルで使用する
    共通データを作成する。

    イベント：
        2024-03-31より前に記録された掲載終了

    右打ち切り：
        2024-03-31まで掲載が続いているレコード

    注意：
        pub_end_date == 2024-03-31 は、
        データ収録期間末日の影響を受けている可能性が高いため、
        掲載終了イベントではなく右打ち切りとして扱う。
    """

    d = df.copy()

    # --------------------------------------------------------
    # 掲載開始日が有効なものだけ使用
    # --------------------------------------------------------

    d = d[
        d["start_date"].notna()
    ].copy()

    # --------------------------------------------------------
    # 掲載開始年を限定
    # --------------------------------------------------------

    if years is None:
        years = TARGET_YEARS

    d = d[
        d["start_year"].isin(years)
    ].copy()

    # --------------------------------------------------------
    # イベント発生の定義
    # --------------------------------------------------------

    # 観測期間末日より前に掲載終了日がある場合のみ
    # 「掲載終了を観測した」とする
    d["event_observed"] = (
        d["end_date"].notna()
        & (
            d["end_date"]
            < OBSERVATION_END
        )
    )

    # --------------------------------------------------------
    # 観測終了日
    # --------------------------------------------------------

    # イベントが観測された場合：
    #   実際の掲載終了日
    #
    # それ以外：
    #   データ収録期間末日
    d["observed_end_date"] = (
        d["end_date"]
        .where(
            d["event_observed"],
            OBSERVATION_END,
        )
    )

    # --------------------------------------------------------
    # 生存時間
    # --------------------------------------------------------

    d["survival_days"] = (
        d["observed_end_date"]
        - d["start_date"]
    ).dt.days.astype(float)

    # --------------------------------------------------------
    # 異常値チェック
    # --------------------------------------------------------

    d = d[
        d["survival_days"].notna()
        & d["survival_days"].ge(0)
    ].copy()

    # --------------------------------------------------------
    # eventを0/1へ
    # --------------------------------------------------------

    d["event"] = (
        d["event_observed"]
        .astype(int)
    )

    return (
        d.reset_index(
            drop=True
        )
    )


# ============================================================
# 生存分析データの確認
# ============================================================

def survival_summary(
    df: pd.DataFrame,
) -> pd.DataFrame:
    """
    生存分析用データの件数を確認する。
    """

    rows = []

    years = sorted(
        df["start_year"]
        .dropna()
        .astype(int)
        .unique()
    )

    for year in years:

        sub = df[
            df["start_year"]
            == year
        ]

        events = int(
            sub["event"].sum()
        )

        censored = int(
            (
                sub["event"]
                == 0
            )
            .sum()
        )

        rows.append(
            {
                "掲載開始年": year,
                "件数": len(sub),
                "掲載終了イベント": events,
                "右打ち切り": censored,
                "右打ち切り率": (
                    censored / len(sub)
                    if len(sub) > 0
                    else 0
                ),
                "観測日数中央値": (
                    sub["survival_days"]
                    .median()
                ),
                "観測日数最大": (
                    sub["survival_days"]
                    .max()
                ),
            }
        )

    return pd.DataFrame(
        rows
    )